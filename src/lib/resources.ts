// One place that describes every CRUD module: its table, columns, and form fields.
// The list, create, edit and delete screens are all generated from this config.

export type FieldType =
  | "text"
  | "textarea"
  | "email"
  | "tel"
  | "number"
  | "money"
  | "date"
  | "datetime"
  | "select"
  | "relation"
  | "boolean";

export type Option = { value: string; label: string };

export type Field = {
  name: string;
  label: string;
  type: FieldType;
  required?: boolean;
  options?: Option[];
  /** For relation fields: the table and column to show in the dropdown */
  relation?: { table: string; labelColumn: string };
  placeholder?: string;
  /** Show this field in the list table */
  list?: boolean;
  /** Span both columns in the form grid */
  wide?: boolean;
  /** Generated by the database; shown in the list but not editable */
  readOnly?: boolean;
};

export type Resource = {
  slug: string;
  table: string;
  title: string;
  singular: string;
  description: string;
  icon: string;
  /** Columns searched by the list's search box */
  searchColumns: string[];
  /** Column used as the record's display name */
  titleColumn: string;
  orderBy: { column: string; ascending: boolean };
  fields: Field[];
};

const opts = (...values: string[]): Option[] =>
  values.map((v) => ({
    value: v,
    label: v.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase()),
  }));

